import fs from 'node:fs/promises';
import path from 'node:path';
import {marked} from 'marked';
import sanitizeHtml from 'sanitize-html';
const contentDir=path.resolve('content/articles');
const target=path.resolve('app/articles/(posts)');
await fs.mkdir(contentDir,{recursive:true});
await fs.mkdir(target,{recursive:true});
const articles=[];
for(const file of (await fs.readdir(contentDir)).filter(f=>f.endsWith('.md'))){
 const raw=await fs.readFile(path.join(contentDir,file),'utf8');
 const match=raw.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n([\s\S]*)$/);
 if(!match)throw new Error(file+': 缺少文章資訊區塊');
 const meta={};
 for(const line of match[1].split(/\r?\n/)){const pair=line.match(/^(\w+):\s*(.*?)\s*$/);if(pair)meta[pair[1]]=pair[2].replace(/^["']|["']$/g,'');}
 if(meta.draft!=='false')continue;
 const slug=file.slice(0,-3);
 if(!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(slug))throw new Error(file+': 檔名請使用英文小寫、數字與連字號');
 for(const key of ['title','description','date','author'])if(!meta[key])throw new Error(file+': 缺少 '+key);
 if(!/^\d{4}-\d{2}-\d{2}$/.test(meta.date)||Number.isNaN(Date.parse(meta.date))||new Date(meta.date).toISOString().slice(0,10)!==meta.date)throw new Error(file+': 日期必須為 YYYY-MM-DD');
 const html=sanitizeHtml(marked.parse(match[2]),{allowedTags:sanitizeHtml.defaults.allowedTags.concat(['img']),allowedAttributes:{...sanitizeHtml.defaults.allowedAttributes,img:['src','alt','width','height','loading']},allowedSchemes:['https','http','mailto']});
 articles.push({...meta,slug,html});
}
articles.sort((a,b)=>b.date.localeCompare(a.date));
await fs.writeFile('lib/articles.generated.json',JSON.stringify(articles,null,2)+'\n');
// Remove only previously generated route files; preserve any manually written files.
for(const entry of await fs.readdir(target,{withFileTypes:true})){
 if(!entry.isDirectory()||articles.some(a=>a.slug===entry.name))continue;
 const p=path.join(target,entry.name,'page.tsx');
 const text=await fs.readFile(p,'utf8').catch(()=>'');
 if(text.startsWith('// Generated by prepare-articles')){await fs.unlink(p);await fs.rmdir(path.dirname(p)).catch(()=>{});}
}
for(const article of articles){
 const folder=path.join(target,article.slug);await fs.mkdir(folder,{recursive:true});
 const source='// Generated by prepare-articles; edit content/articles instead.\nimport Article from "@/app/article";\nconst article='+JSON.stringify(article)+';\nexport const metadata={title:article.title,description:article.description};\nexport default function Page(){return <Article article={article}/>;}\n';
 await fs.writeFile(path.join(folder,'page.tsx'),source);
}
console.log('Prepared '+articles.length+' published articles.');
